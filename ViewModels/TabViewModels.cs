namespace TweakFirmware.ViewModels
{
    /// <summary>
    /// Состояние вкладок, живущее дольше самих страниц.
    ///
    /// NavigationView создаёт страницу заново при каждом переходе. Пока каждая страница
    /// создавала себе и ViewModel, вместе со страницей пропадало всё введённое: выбранный
    /// файл, папка назначения, пресет, ожидаемый хэш, список файлов для сравнения и его
    /// результат, недописанное письмо в «Обратной связи». Достаточно было заглянуть
    /// в «Настройки» и вернуться.
    ///
    /// Теперь страница — только разметка, а состояние лежит здесь и переживает переходы.
    /// Держать так можно именно потому, что вкладок ровно столько и они существуют всё
    /// время работы программы: это не кэш, который надо когда-то сбрасывать.
    ///
    /// «Настройки» сюда не входят намеренно: своего состояния у них нет, они читают
    /// и пишут напрямую в сервисы, поэтому заново созданная ViewModel всегда показывает
    /// актуальное.
    /// </summary>
    public static class TabViewModels
    {
        public static ConvertViewModel ConvertTab { get; } = new();
        public static MergeViewModel MergeTab { get; } = new();
        public static VerifyViewModel VerifyTab { get; } = new();
        public static ExtractViewModel ExtractTab { get; } = new();
        public static AboutViewModel AboutTab { get; } = new();
    }
}
