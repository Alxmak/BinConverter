using System.Collections.Generic;
using System.IO;

namespace TweakFirmware.Core
{
    /// <summary>
    /// Ровная ли цепочка частей по размерам.
    ///
    /// Нарезка всегда даёт части одного размера, а меньше — только последнюю: сколько
    /// осталось, столько в неё и легло. Размер при этом любой, он берётся из лимита
    /// программатора или из поля ввода, поэтому сравнивать части нужно между собой,
    /// а не с каким-то «правильным» числом. Из-за этого проверка ничего не говорит
    /// о нашей нарезке при любом лимите — и срабатывает ровно там, где цепочка
    /// действительно неровная.
    ///
    /// Ради чего: часть, скопированная не до конца, лежит на месте и называется верно —
    /// по имени такую не отличить, а собранный из неё файл будет испорчен ровно с того
    /// места, где обрывается эта часть. Проверка идёт по метаданным, содержимое частей
    /// не читается.
    ///
    /// Отказом это не считается: цепочку могла нарезать другая программа, и «неровно»
    /// там может быть нормой. Поэтому метод только сообщает о находке, а решение —
    /// предупредить и продолжить — принимает вызывающий.
    /// </summary>
    public static class ChainConsistency
    {
        /// <summary>
        /// Номер первой части, размер которой не совпадает с размером предыдущих
        /// (нумерация как в интерфейсе: 1 — базовый файл). Возвращает null, если цепочка
        /// ровная, состоит из одного файла или размеры узнать не удалось.
        /// </summary>
        public static int? FindUnevenPartNumber(IReadOnlyList<string> chain)
        {
            // Меньше трёх файлов сравнивать не с чем: у цепочки из двух вторая часть —
            // последняя, а последней быть меньше остальных как раз положено.
            if (chain.Count < 3) return null;

            try
            {
                long expected = new FileInfo(chain[0]).Length;

                // Последнюю часть не проверяем: она короче остальных у любой нормальной
                // цепочки, кроме случая, когда размер дампа кратен лимиту.
                for (int i = 1; i < chain.Count - 1; i++)
                {
                    if (new FileInfo(chain[i]).Length != expected) return i + 1;
                }

                // Хвост длиннее полной части — это уже не «остаток», а что-то чужое.
                return new FileInfo(chain[^1]).Length > expected ? chain.Count : null;
            }
            catch (IOException)
            {
                // Размер не спросить — молчим: предупреждать о том, чего не знаем, нельзя.
                return null;
            }
        }
    }
}
